        assert f2(pol["mean_order_quantity"]) in section, name
        assert f5(p["mean_difference"]) in section, name
        assert f5(p["ci95_low"]) in section, f"{name} ci95_low"
        assert f5(p["ci95_high"]) in section, f"{name} ci95_high"
