def test_the_artifact_carries_a_provenance_git_block(artifact: dict) -> None:
    """
    Every generator under `seeds/` stamps a `git` block (see `seeds/provenance.py`) so a
    reader can tell whether an artifact came from a clean commit. This does not assert
    `dirty is False`: this generator was written and run alongside several other
    concurrent workstreams sharing one tree (see `git log`), so a dirty flag at
    generation time is an expected fact of that sandbox, not a defect in this generator.
    What must hold is that the block exists and is well-formed, so a reader CAN check
    reproducibility later -- `test_docs_match_artifacts.py::
    test_the_leakage_artifact_was_generated_from_a_clean_tree` is the sibling test that
    enforces `dirty is False` once an artifact is committed for real.
    """
    git = artifact["provenance"]["git"]
    assert isinstance(git.get("dirty"), bool)
    assert git.get("commit"), "provenance records no git commit"


